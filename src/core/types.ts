/**
 * Обработчик ошибок, возникающих в слушателях.
 * Позволяет изолировать падение одного слушателя от остальных
 * и централизованно логировать/репортить ошибки.
 *
 * @param error - пойманная ошибка (может быть любого типа)
 * @param context - строковый контекст, где произошла ошибка (например, 'EventEmitter.emit')
 */
export type ErrorHandler = (error: unknown, context: string) => void;

/**
 * Минимальный интерфейс источника значений, на который можно подписаться.
 *
 * Намеренно не зависит от {@link Observable}, чтобы слой DOM не тащил
 * зависимость на реактивный слой. Любой `Observable<T>` структурно
 * совместим с этим интерфейсом.
 *
 * @template T - тип передаваемого значения
 */
export interface Subscribable<T> {
  /**
   * Подписывает обработчик на изменения значения.
   * @param listener - функция-обработчик
   * @returns функция для отписки
   */
  subscribe(listener: (value: T) => void): () => void;
}
